#!/usr/bin/env python3
"""Turns one day of Claude Code and Codex sessions into one sheet of diary material: what the person typed, the AI's
replies, and that day's commits.

Standard library only. Records and repositories are only read. The output holds conversation text, so keep it out of
public repositories. Days are cut by message time (this computer's time zone), not by session start, so a session that
runs past midnight is split by date.

Example: python3 day_sessions.py --date 2026-11-02 --out "$TMPDIR/hus-session-coach-material.md"
"""
import argparse
import datetime
import glob
import json
import os
import re
import subprocess
import sys
from collections import Counter

import i18n

PREFIX = "[hus-session-coach]"

# Text that tools put in the user's place. A message that starts with one of these tags was not typed by a person.
INJECTED_TAGS = (
    "command-name", "command-message", "command-args",
    "local-command-stdout", "local-command-stderr", "local-command-caveat",
    "task-notification", "system-reminder", "bash-input", "bash-stdout", "bash-stderr",
    "environment_context", "user_instructions", "turn_aborted", "user_shell_command",
)
INJECTED_PREFIXES = (
    "[Request interrupted",
    "Caveat: The messages below were generated by the user while running local commands",
    "# AGENTS.md instructions",
    "This session is being continued from a previous conversation",
)
STRIP_BLOCKS = ("system-reminder", "ide_selection", "ide_opened_file", "ide_diagnostics")
# Temporary folders used by automated runs (tests, sub-tasks). Not a record of a person working.
TEMP_ROOTS = ("/tmp/", "/private/tmp/", "/var/folders/", "/private/var/folders/")
SECRET_RES = [
    re.compile(r"\b(?:sk|pk|rk)-[A-Za-z0-9_-]{16,}"),
    re.compile(r"\b(?:ghp|gho|ghs|github_pat)_[A-Za-z0-9_]{16,}"),
    re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----.*?(?:-----END [A-Z ]*PRIVATE KEY-----|\Z)", re.S),
    re.compile(r"(?i)\b(password|passwd|api[_-]?key|secret|token)\b(\s*[:=]\s*)\S+"),
]
SHORT_CHARS = 10
# A gap between messages longer than this counts as a break and is left out of active time.
IDLE_MINUTES = 30
# This many short sessions that open with the same instruction are taken to be run by a program.
TEMPLATE_CHARS = 18
TEMPLATE_SESSIONS = 3
TEMPLATE_MAX_TURNS = 2
PASTE_KEEP = 300
USER_KEEP = 1200
AI_KEEP = 300
# The AI reply before a short question is kept longer, to see whether the question asked something it already said.
AI_BEFORE_QUESTION_KEEP = 800
QUESTION_MAX_CHARS = 40
# Endings that mark a short question, from every language file (locales/<code>.json match.question_endings).
QUESTION_ENDINGS = tuple(sorted({e for v in i18n.every("match.question_endings").values() for e in v.split("|") if e}))
REDACTED = "[redacted]"


def mask(text):
    for rx in SECRET_RES[:-1]:
        text = rx.sub(REDACTED, text)
    return SECRET_RES[-1].sub(lambda m: m.group(1) + m.group(2) + REDACTED, text)


def clean_user_text(text):
    """Keeps only what the person typed. Empty when a person did not type it."""
    if not isinstance(text, str):
        return ""
    t = text.strip()
    if not t:
        return ""
    m = re.match(r"<([A-Za-z_-]+)", t)
    if (m and m.group(1) in INJECTED_TAGS) or t.startswith(INJECTED_PREFIXES):
        return ""
    for tag in STRIP_BLOCKS:
        t = re.sub(r"<%s\b[^>]*>.*?</%s>" % (tag, tag), "", t, flags=re.S)

    def paste(mt):
        body = mt.group(1).strip()
        more = " ...(+%d chars)" % (len(body) - PASTE_KEEP) if len(body) > PASTE_KEEP else ""
        return "[pasted] " + body[:PASTE_KEEP] + more

    # The closing tag may carry an id too, or be missing.
    t = re.sub(r"<pasted_content\b[^>]*>(.*?)(?:</pasted_content\b[^>]*>|\Z)", paste, t, flags=re.S)
    return t.strip()


def clip(text, limit):
    """Keeps the head and the tail. AI replies often end with a question or a warning."""
    if len(text) <= limit:
        return text
    head = limit * 2 // 3
    tail = limit - head
    return "%s ...(%d chars cut)... %s" % (text[:head], len(text) - limit, text[-tail:])


def repo_root(cwd):
    """A worktree is grouped under its original repository."""
    if not cwd:
        return None
    for marker in ("/.claude/worktrees/", "/.codex/worktrees/", "/.worktrees/"):
        if marker in cwd:
            return cwd.split(marker)[0]
    return cwd.rstrip("/") or "/"


def is_temp(cwd):
    return bool(cwd) and (cwd + "/").startswith(TEMP_ROOTS)


def local_time(value):
    if not value:
        return None
    try:
        return datetime.datetime.fromisoformat(str(value).replace("Z", "+00:00")).astimezone()
    except ValueError:
        return None


def read_jsonl(path, stats):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if line:
                    try:
                        row = json.loads(line)
                    except ValueError:
                        stats["lines that could not be parsed"] += 1
                        continue
                    if isinstance(row, dict):
                        yield row
    except OSError:
        stats["files that could not be read"] += 1


def block_texts(content, kind="text"):
    if isinstance(content, str):
        return [content]
    return [b.get("text", "") for b in (content or []) if isinstance(b, dict) and b.get("type") == kind]


def add_turn(turns, role, text, when):
    """Rows of the same role in a row become one turn. A user message recorded twice is kept once."""
    if not text:
        return
    if turns and turns[-1]["role"] == role:
        if role == "user" and turns[-1]["text"] == text:
            return
        turns[-1]["text"] += "\n\n" + text
        return
    turns.append({"role": role, "text": text, "at": when})


def parse_claude(path, day, stats):
    turns, cwd, sid, is_headless = [], None, None, False
    for o in read_jsonl(path, stats):
        if o.get("type") not in ("user", "assistant") or o.get("isSidechain"):
            continue
        cwd = cwd or o.get("cwd")
        sid = sid or o.get("sessionId")
        # A run launched by a program (claude -p, the SDK). Not typed by a person even when it runs in a project folder.
        is_headless = is_headless or str(o.get("entrypoint") or "").startswith("sdk")
        when = local_time(o.get("timestamp"))
        if when is None or when.date() != day:
            continue
        content = (o.get("message") or {}).get("content")
        if o["type"] == "user":
            origin = o.get("origin")
            is_machine = isinstance(origin, dict) and origin.get("kind") not in (None, "human")
            if o.get("isMeta") or o.get("isCompactSummary") or is_machine:
                continue
            parts = (clean_user_text(x) for x in block_texts(content))
            add_turn(turns, "user", "\n".join(p for p in parts if p), when)
        else:
            parts = (p.strip() for p in block_texts(content))
            add_turn(turns, "assistant", "\n".join(p for p in parts if p), when)
    return {"tool": "Claude Code", "id": sid or os.path.splitext(os.path.basename(path))[0], "cwd": cwd, "turns": turns,
            "is_headless": is_headless}


def codex_imported_ids(root):
    """Ids of sessions Codex imported from another tool. They duplicate the originals, so they are left out."""
    try:
        with open(os.path.join(root, "external_agent_session_imports.json"), encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError):
        return set()
    recs = data.get("records", []) if isinstance(data, dict) else []
    return {r.get("imported_thread_id") for r in recs if isinstance(r, dict) and r.get("imported_thread_id")}


def parse_codex(path, day, stats):
    meta = {}
    typed, fallback, assistant = [], [], []
    for seq, o in enumerate(read_jsonl(path, stats)):
        typ, p, when = o.get("type"), o.get("payload") or {}, local_time(o.get("timestamp"))
        if typ == "session_meta" and not meta:
            meta = p
        elif typ == "event_msg" and p.get("type") == "user_message":
            typed.append((seq, when, p.get("message", "")))
        elif typ == "event_msg" and p.get("type") == "item_completed" and (p.get("item") or {}).get("type") == "UserMessage":
            blocks = (p.get("item") or {}).get("content") or []
            typed.append((seq, when, "\n".join((b.get("text") or "") for b in blocks if isinstance(b, dict))))
        elif typ == "response_item" and p.get("type") == "message":
            if p.get("role") == "user":
                fallback.append((seq, when, "\n".join(block_texts(p.get("content"), "input_text"))))
            elif p.get("role") == "assistant":
                assistant.append((seq, when, "\n".join(block_texts(p.get("content"), "output_text")).strip()))
    # Typed messages are recorded as events. Only the older format without events falls back to the model input.
    events = [(s, w, "user", clean_user_text(t)) for s, w, t in (typed or fallback)]
    events += [(s, w, "assistant", t) for s, w, t in assistant]
    turns = []
    for _, when, role, text in sorted(events, key=lambda e: e[0]):
        if when is not None and when.date() == day:
            add_turn(turns, role, text, when)
    source = meta.get("source")
    return {
        "tool": "Codex",
        "id": meta.get("id") or os.path.splitext(os.path.basename(path))[0],
        "cwd": meta.get("cwd"),
        "turns": turns,
        "is_subagent": isinstance(source, dict) and "subagent" in source,
        # A run started with codex exec. Not a conversation with a person.
        "is_headless": source == "exec" or meta.get("originator") == "codex_exec",
    }


def recent_files(pattern, day):
    """A file last written before that day cannot hold messages from that day."""
    start = datetime.datetime.combine(day, datetime.time.min).astimezone().timestamp()
    for path in glob.glob(pattern, recursive=True):
        try:
            if os.path.getmtime(path) >= start:
                yield path
        except OSError:
            pass


def collect(args, day, stats):
    skip = {x for x in args.exclude_session if x}
    found = {}
    # Only top-level <project>/<session>.jsonl. Files under <session>/subagents/ are subagent records.
    claude = os.path.join(os.path.expanduser(args.claude_dir), "*", "*.jsonl")
    for path in recent_files(claude, day):
        s = parse_claude(path, day, stats)
        found[("claude", s["id"])] = max(s, found.get(("claude", s["id"]), s), key=lambda x: len(x["turns"]))
    root = os.path.expanduser(args.codex_dir)
    imported = codex_imported_ids(root)
    for pattern in ("sessions/**/*.jsonl", "archived_sessions/*.jsonl"):
        for path in recent_files(os.path.join(root, pattern), day):
            s = parse_codex(path, day, stats)
            if s.pop("is_subagent"):
                stats["left out: subagent"] += 1
            elif s["id"] in imported:
                stats["left out: copy imported from another tool"] += 1
            else:
                found[("codex", s["id"])] = max(s, found.get(("codex", s["id"]), s), key=lambda x: len(x["turns"]))

    kept = []
    for s in found.values():
        users = [t for t in s["turns"] if t["role"] == "user"]
        if not users:
            continue
        if s["id"] in skip:
            stats["left out: this conversation"] += 1
        elif is_temp(s["cwd"]):
            stats["left out: automated run in a temporary folder"] += 1
        elif s.get("is_headless"):
            stats["left out: launched by a program"] += 1
        else:
            kept.append(s)
    return sorted(drop_templated(kept, stats), key=lambda s: s["turns"][0]["at"])


def drop_templated(sessions, stats):
    """Drops groups of short sessions that open with the same instruction. Automated runs inherit the parent's
    entrypoint, so there is no other signal."""
    def is_short(s):
        return sum(1 for t in s["turns"] if t["role"] == "user") <= TEMPLATE_MAX_TURNS

    def opening(s):
        return next(t["text"] for t in s["turns"] if t["role"] == "user")[:TEMPLATE_CHARS]

    counts = Counter(opening(s) for s in sessions if is_short(s))
    kept = []
    for s in sessions:
        if is_short(s) and counts[opening(s)] >= TEMPLATE_SESSIONS:
            stats["left out: looks automated (same opening instruction)"] += 1
        else:
            kept.append(s)
    return kept


def git_output(root, *args):
    """git output, or None when it is not a repository or git fails."""
    try:
        out = subprocess.run(["git", "-C", root, *args], capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout.strip() if out.returncode == 0 else None


def repos_for(folder):
    """Repositories for a session folder. When the folder is not a repository, look one level down."""
    top = git_output(folder, "rev-parse", "--show-toplevel")
    if top:
        return [top]
    try:
        names = sorted(os.listdir(folder))
    except OSError:
        return []
    return [os.path.join(folder, n) for n in names if os.path.exists(os.path.join(folder, n, ".git"))]


def commits(sessions, day, stats):
    """Commits that day authored as the person, in the repositories where sessions were opened.
    Commits made by AI can carry the person's name too."""
    start, end = day.isoformat(), (day + datetime.timedelta(days=1)).isoformat()
    result = {}
    seen, hashes = set(), set()
    for folder in sorted({repo_root(s["cwd"]) for s in sessions} - {None}):
        repos = repos_for(folder)
        if not repos:
            stats["could not read commits in folder " + os.path.basename(folder)] += 1
        for root in repos:
            if root in seen:
                continue
            seen.add(root)
            cmd = ["log", "--all", "--no-merges", "--since=%sT00:00:00" % start, "--until=%sT00:00:00" % end,
                   "--date=format:%H:%M", "--pretty=%ad %h %s"]
            email = git_output(root, "config", "user.email")
            if email:
                cmd.append("--author=" + email)
            out = git_output(root, *cmd)
            if out is None:
                stats["could not read commits in folder " + os.path.basename(root)] += 1
                continue
            # Copies of the same repository (dev, use, ...) show the same commits again.
            lines = [l for l in (out.splitlines() if out else []) if commit_hash(l) not in hashes]
            hashes.update(commit_hash(l) for l in lines)
            if lines:
                result[os.path.basename(root)] = (len(lines), group_commits(reversed(lines)))
    return result


def commit_hash(line):
    parts = line.split(" ", 2)
    return parts[1] if len(parts) > 1 else line


def empty_usage():
    return {"mine": Counter(), "sub": Counter(), "auto": Counter(), "models": Counter()}


def claude_rows_usage(path, day, stats):
    """Tokens per message that day. One message is recorded once per block, so rows are grouped by message id."""
    found = {}
    for o in read_jsonl(path, stats):
        if o.get("type") != "assistant":
            continue
        message = o.get("message") or {}
        tokens = message.get("usage")
        when = local_time(o.get("timestamp"))
        if not tokens or when is None or when.date() != day:
            continue
        key = (message.get("id"), o.get("requestId"))
        row = {"new": (tokens.get("input_tokens") or 0) + (tokens.get("cache_creation_input_tokens") or 0),
               "cache": tokens.get("cache_read_input_tokens") or 0,
               "out": tokens.get("output_tokens") or 0, "model": message.get("model") or "?"}
        if key not in found or row["out"] > found[key]["out"]:
            found[key] = row
    return found


def add_tokens(usage, kind, row):
    for name in ("new", "cache", "out"):
        usage[kind][name] += row[name]
    usage["models"][row["model"]] += row["new"] + row["out"]


def codex_tokens(path, day, stats):
    """Token records are running totals: count only what grew that day. Input includes cache reads, so they are taken out."""
    prev = Counter()
    gained = Counter()
    for o in read_jsonl(path, stats):
        p = o.get("payload") or {}
        total = (p.get("info") or {}).get("total_token_usage") if p.get("type") == "token_count" else None
        when = local_time(o.get("timestamp"))
        if not total or when is None:
            continue
        now = Counter(new=(total.get("input_tokens") or 0) - (total.get("cached_input_tokens") or 0),
                      cache=total.get("cached_input_tokens") or 0, out=total.get("output_tokens") or 0)
        if when.date() == day:
            for name in now:
                gained[name] += max(0, now[name] - prev[name])
        prev = now
    return gained


def day_usage(args, day, kept, stats):
    """Tokens used that day, split into the person's sessions, their subagents, and automated runs.
    A resumed session that records old messages again is counted once."""
    usage = empty_usage()
    mine = {s["id"] for s in kept}
    seen = set()
    root = os.path.expanduser(args.claude_dir)
    groups = [(os.path.join(root, "*", "*.jsonl"), lambda p: "mine" if os.path.splitext(os.path.basename(p))[0] in mine else "auto"),
              (os.path.join(root, "*", "*", "subagents", "*.jsonl"),
               lambda p: "sub" if os.path.basename(os.path.dirname(os.path.dirname(p))) in mine else "auto")]
    for pattern, classify in groups:
        for path in recent_files(pattern, day):
            for key, row in claude_rows_usage(path, day, stats).items():
                if key not in seen:
                    seen.add(key)
                    add_tokens(usage, classify(path), row)
    codex = os.path.expanduser(args.codex_dir)
    imported = codex_imported_ids(codex)
    for pattern in ("sessions/**/*.jsonl", "archived_sessions/*.jsonl"):
        for path in recent_files(os.path.join(codex, pattern), day):
            meta = next(read_jsonl(path, stats), {}).get("payload") or {}
            if meta.get("id") in imported:
                continue
            gained = codex_tokens(path, day, stats)
            kind = "mine" if meta.get("id") in mine else "auto"
            usage[kind].update(gained)
            usage["models"]["Codex"] += gained["new"] + gained["out"]
    return usage


def usage_lines(usage):
    """Token figures for the material. Cache reads re-read the same content, so they are listed apart from new input."""
    def row(name, c):
        return "  - %s: new input %s, cache reads %s, output %s" % (name, format(c["new"], ","), format(c["cache"], ","), format(c["out"], ","))

    lines = ["- Tokens", row("my sessions", usage["mine"]), row("their subagents", usage["sub"]), row("automated runs", usage["auto"])]
    models = [(m, n) for m, n in usage["models"].most_common() if n]
    if models:
        lines.append("  - by model (new input + output): " + ", ".join("%s %s" % (m, format(n, ",")) for m, n in models))
    return lines


def group_commits(lines):
    """Repeated subjects (automatic snapshots and the like) become one line. Line form: time hash subject."""
    groups = {}
    for line in lines:
        parts = line.split(" ", 2)
        subject = parts[2] if len(parts) == 3 else line
        groups.setdefault(subject, []).append(line)
    return ["%s (%d with the same subject)" % (g[0], len(g)) if len(g) > 1 else g[0] for g in groups.values()]


def facts(sessions):
    users = [t for s in sessions for t in s["turns"] if t["role"] == "user"]
    times = sorted(t["at"] for t in users)
    active = sum(min((b - a).total_seconds(), IDLE_MINUTES * 60) if (b - a).total_seconds() <= IDLE_MINUTES * 60 else 0
                 for a, b in zip(times, times[1:]))
    return {
        "sessions": len(sessions),
        "by_tool": Counter(s["tool"] for s in sessions),
        "by_project": Counter(os.path.basename(repo_root(s["cwd"]) or "(unknown)") for s in sessions),
        "user_turns": len(users),
        "short_turns": sum(1 for t in users if len(t["text"]) <= SHORT_CHARS),
        "first": times[0].strftime("%H:%M") if times else "-",
        "last": times[-1].strftime("%H:%M") if times else "-",
        "active_minutes": round(active / 60),
    }


def is_question(text):
    return len(text) <= QUESTION_MAX_CHARS and text.rstrip().endswith(QUESTION_ENDINGS)


def render(day, sessions, commit_map, stats, ai_keep=AI_KEEP, question_keep=AI_BEFORE_QUESTION_KEEP, usage=None):
    f = facts(sessions)
    tools = ", ".join("%s %d" % kv for kv in f["by_tool"].most_common())
    projects = ", ".join("%s %d" % kv for kv in f["by_project"].most_common())
    out = ["# Diary material for %s" % day.isoformat(), "", "## Facts (counted by the script)",
           "- Sessions: %d (%s)" % (f["sessions"], tools or "none"),
           "- By project: %s" % (projects or "none"),
           "- My messages: %d, of which %d short ones of %d characters or fewer" % (f["user_turns"], f["short_turns"], SHORT_CHARS),
           "- First message %s, last message %s, active about %d min (gaps over %d min left out, rough)" % (
               f["first"], f["last"], f["active_minutes"], IDLE_MINUTES),
           ]
    out += ["- %s: %d" % kv for kv in sorted(stats.items())]
    if usage:
        out += usage_lines(usage)
    out += ["", "## Commits that day (authored as me; commits made by AI are included too)"]
    if commit_map:
        for project, (total, lines) in commit_map.items():
            out.append("- %s: %d" % (project, total))
            out += ["  - " + mask(line) for line in lines]
    else:
        out.append("- None. If folders whose commits could not be read are listed above, commits there were not seen")
    for s in sessions:
        turns = s["turns"]
        users = sum(1 for t in turns if t["role"] == "user")
        out += ["", "## Session %s · %s · %s~%s · %d messages from me" % (
            os.path.basename(repo_root(s["cwd"]) or "(unknown)"), s["tool"],
            turns[0]["at"].strftime("%H:%M"), turns[-1]["at"].strftime("%H:%M"), users)]
        for i, t in enumerate(turns):
            if t["role"] == "user":
                who, keep = "me", USER_KEEP
            else:
                after = turns[i + 1] if i + 1 < len(turns) else None
                who, keep = "AI", question_keep if after and is_question(after["text"]) else ai_keep
            out.append("[%s %s] %s" % (t["at"].strftime("%H:%M"), who, mask(clip(t["text"], keep))))
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--date", help="YYYY-MM-DD. Today when left out")
    ap.add_argument("--claude-dir", default="~/.claude/projects")
    ap.add_argument("--codex-dir", default="~/.codex")
    ap.add_argument("--exclude-session", action="append",
                    default=[os.environ.get("CLAUDE_CODE_SESSION_ID"), os.environ.get("CODEX_THREAD_ID")],
                    help="session id to leave out. This conversation is left out through its environment variable")
    ap.add_argument("--out", required=True, help="output path. Keep it out of public repositories")
    args = ap.parse_args(argv)

    day = datetime.date.fromisoformat(args.date) if args.date else datetime.date.today()
    stats = Counter()
    sessions = collect(args, day, stats)
    commit_map = commits(sessions, day, stats)
    text = render(day, sessions, commit_map, stats)
    out = os.path.expanduser(args.out)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    print("%s %d sessions, %d characters -> %s" % (PREFIX, len(sessions), len(text), out))
    for key, value in stats.items():
        print("  %s: %d" % (key, value))
    return 0


if __name__ == "__main__":
    sys.exit(main())
